def run_all_tests():
    """Run all tests in sequence"""
    print("\n" + "="*60)
    print("  CONTENT LAYER TEST SUITE")
    print("  Testing content creation, approval, and lifecycle")
    print("="*60)
    
    tests = [
        test_1_create_workspace,
        test_2_create_workflow_with_caption_generator,
        test_3_run_workflow,
        test_4_list_content,
        test_5_get_content_details,
        test_6_approve_content,
        test_7_update_content_status,
        test_8_get_pending_content
    ]
    
    results = []
    for test in tests:
        try:
            result = test()
            results.append(result)
            if not result:
                print("\n⚠️  Test failed, but continuing...")
        except Exception as e:
            print(f"\n❌ Test exception: {str(e)}")
            results.append(False)
    
    # Summary
    print("\n" + "="*60)
    print("  TEST SUMMARY")
    print("="*60)
    passed = sum(results)
    total = len(results)
    print(f"Passed: {passed}/{total}")
    print(f"Failed: {total - passed}/{total}")
    
    if passed == total:
        print("\n✅ ALL TESTS PASSED!")
    else:
        print(f"\n⚠️  {total - passed} test(s) failed")

if __name__ == "__main__":
    run_all_tests()
