def print_section(title):
    print(f"\n{'='*60}")
    print(f"  {title}")
    print('='*60)

def test_1_create_workspace():
    """Step 1: Create a test workspace"""
    global WORKSPACE_ID
    
    print_section("TEST 1: Create Workspace")
    
    # Generate a test user_id (in production this would come from auth)
    import uuid
    user_id = str(uuid.uuid4())
    
    response = requests.post(
        f"{BASE_URL}/api/workspaces",
        json={
            "owner_user_id": user_id,
            "name": "Content Test Workspace"
        }
    )
    
    print(f"Status: {response.status_code}")
    data = response.json()
    print(f"Response: {json.dumps(data, indent=2, default=str)}")
    
    if response.status_code == 200:
        WORKSPACE_ID = data["id"]
        print(f"✅ Workspace created: {WORKSPACE_ID}")
        return True
    else:
        print(f"❌ Failed to create workspace")
        return False

