def test_3_run_workflow():
    """Step 3: Run the workflow to generate content"""
    global JOB_ID
    
    print_section("TEST 3: Run Workflow")
    
    if not WORKFLOW_ID:
        print("❌ No workflow ID available")
        return False
    
    response = requests.post(f"{BASE_URL}/api/workflows/{WORKFLOW_ID}/run")
    
    print(f"Status: {response.status_code}")
    data = response.json()
    print(f"Response: {json.dumps(data, indent=2, default=str)}")
    
    if response.status_code == 200:
        JOB_ID = data["job_id"]
        print(f"✅ Job started: {JOB_ID}")
        print("⏳ Waiting for job to complete...")
        
        # Poll job status
        import time
        max_attempts = 30
        for attempt in range(max_attempts):
            time.sleep(2)
            status_response = requests.get(f"{BASE_URL}/api/jobs/{JOB_ID}")
            if status_response.status_code == 200:
                job_data = status_response.json()
                status = job_data.get("status")
                progress = job_data.get("progress", 0)
                print(f"  Attempt {attempt + 1}: Status={status}, Progress={progress}%")
                
                if status == "completed":
                    print("✅ Job completed successfully")
                    return True
                elif status == "failed":
                    print(f"❌ Job failed: {job_data.get('error')}")
                    return False
        
        print("⏱️ Job still running after 60 seconds")
        return False
    else:
        print(f"❌ Failed to start workflow")
        return False

